import numpy as np
import pandas as pd
from tqdm import tqdm


def _forecast_row(sample_idx, quantile_array, quantile_levels, label_entry):
    prediction_length = len(label_entry["target"])
    forecast = {
        f"quantile_{quantile_index}": [
            quantile_array[:, step, :, quantile_index].squeeze()
            for step in range(prediction_length)
        ]
        for quantile_index in range(len(quantile_levels))
    }
    return {
        "sample_idx": sample_idx,
        "final_pred": forecast,
        "future_start": label_entry["start"],
        "frequency": label_entry["freq"],
    }


def get_gift_ensemble_predictions_df(dataset, model_pipeline, include_member_forecasts=False):
    """Run an ensemble pipeline over windows generated by a GIFT-Eval dataset."""
    test_data = dataset.test_data
    results = []
    member_results = {}
    for sample_idx, (input_entry, label_entry) in enumerate(
        tqdm(zip(test_data.input, test_data.label), total=len(test_data))
    ):
        data = np.asarray(input_entry["target"], dtype=float).tolist()
        prediction_length = len(label_entry["target"])
        model_kwargs = {"prediction_length": [prediction_length]}
        if "item_id" in input_entry:
            model_kwargs["series_ids"] = [input_entry["item_id"]]
        output = model_pipeline([data], **model_kwargs)
        quantile_levels = output.metadata["quantile_levels"]
        quantile_array = np.asarray(output.predicted_quantiles)
        results.append(
            _forecast_row(sample_idx, quantile_array, quantile_levels, label_entry)
        )
        if include_member_forecasts:
            for member in model_pipeline.members:
                member_forecast = getattr(member, "last_forecast", None)
                if member_forecast is None:
                    continue
                member_name = member.model_name
                member_results.setdefault(member_name, []).append(
                    _forecast_row(
                        sample_idx,
                        np.asarray(member_forecast),
                        quantile_levels,
                        label_entry,
                    )
                )

    ensemble_frame = pd.DataFrame(results)
    if include_member_forecasts:
        return ensemble_frame, {
            member_name: pd.DataFrame(rows)
            for member_name, rows in member_results.items()
        }
    return ensemble_frame


def get_test_window_lengths(dataset):
    """Return the minimum history length and maximum horizon in test windows."""
    min_context_length = None
    max_prediction_length = None
    test_data = dataset.test_data
    for input_entry, label_entry in zip(test_data.input, test_data.label):
        context_length = len(input_entry["target"])
        prediction_length = len(label_entry["target"])
        min_context_length = (
            context_length
            if min_context_length is None
            else min(min_context_length, context_length)
        )
        max_prediction_length = (
            prediction_length
            if max_prediction_length is None
            else max(max_prediction_length, prediction_length)
        )

    if min_context_length is None or max_prediction_length is None:
        raise ValueError("GIFT-Eval test data contains no windows")
    return min_context_length, max_prediction_length
